export function Icon({
  name,
  size = 16,
  filled = false,
  className,
  label,
}: {
  name: string
  size?: number
  filled?: boolean
  className?: string
  label?: string
}) {
  const Cmp = ICONS[name] ?? Circle
  return (
    <Cmp
      size={size}
      weight={filled ? 'fill' : 'regular'}
      className={cn('qy-icon', className)}
      aria-hidden={label ? undefined : true}
      aria-label={label}
      role={label ? 'img' : undefined}
    />
  )
}
